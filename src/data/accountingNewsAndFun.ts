/**
 * Fetch Accounting News from Internet RSS Feeds (no AI)
 * Falls back to verified curated list if external RSS times out or blocks
 */
export async function fetchInternetAccountingNews(category?: string): Promise<AccountingNewsItem[]> {
  const onlineRssUrls = [
    "https://www.irna.ir/rss/tp/20", // IRNA Economy & Tax
    "https://www.tasnimnews.com/fa/rss/feed/0/7/0/%D8%A7%D9%82%D8%AA%D8%B5%D8%A7%D8%AF%DB%8C", // Tasnim Economy
  ];

  let fetchedItems: AccountingNewsItem[] = [];

  for (const url of onlineRssUrls) {
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 2500); // quick 2.5s timeout

      const response = await fetch(url, {
        headers: {
          "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko)",
          "Accept": "application/rss+xml, application/xml, text/xml, */*",
        },
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (response.ok) {
        const xmlText = await response.text();
        const parsed = parseRssFeed(xmlText);
        if (parsed.length > 0) {
          fetchedItems = [...fetchedItems, ...parsed];
        }
      }
    } catch {
      // Ignore network failures in sandbox or offline mode
    }
  }

  // Combine fetched online news with verified Iranian accounting/tax news items
  const allItems = [...fetchedItems, ...verifiedAccountingNews];

  if (category && category !== "all") {
    return allItems.filter((i) => i.category.includes(category) || i.tags.some((t) => t.includes(category)));
  }

  return allItems;
}

/**
 * Simple Regex-based RSS parser (lightweight, zero external dependency, ultra safe)
 */
function parseRssFeed(xml: string): AccountingNewsItem[] {
  const items: AccountingNewsItem[] = [];
  const itemMatches = xml.match(/<item[\s\S]*?<\/item>/gi) || [];

  for (let i = 0; i < Math.min(itemMatches.length, 5); i++) {
    const itemXml = itemMatches[i];
    const titleMatch = itemXml.match(/<title><!\[CDATA\[([\s\S]*?)\]\]><\/title>/i) || itemXml.match(/<title>([\s\S]*?)<\/title>/i);
    const linkMatch = itemXml.match(/<link><!\[CDATA\[([\s\S]*?)\]\]><\/link>/i) || itemXml.match(/<link>([\s\S]*?)<\/link>/i);
    const descMatch = itemXml.match(/<description><!\[CDATA\[([\s\S]*?)\]\]><\/description>/i) || itemXml.match(/<description>([\s\S]*?)<\/description>/i);
    const dateMatch = itemXml.match(/<pubDate>([\s\S]*?)<\/pubDate>/i);

    const title = cleanText(titleMatch ? titleMatch[1] : "");
    const summary = cleanText(descMatch ? descMatch[1] : "");
    const link = linkMatch ? linkMatch[1].trim() : "";
    const pubDate = dateMatch ? "امروز" : "امروز";

    // Only include tax/accounting/financial relevant titles
    const isAccountingRelevant =
      title.includes("مالیات") ||
      title.includes("مودیان") ||
      title.includes("حساب") ||
      title.includes("بورس") ||
      title.includes("کارگر") ||
      title.includes("دستمزد") ||
      title.includes("بودجه") ||
      title.includes("بانک") ||
      title.includes("ارزش افزوده") ||
      summary.includes("مالیات") ||
      summary.includes("حسابداری");

    if (title && isAccountingRelevant) {
      items.push({
        id: `rss-online-${Date.now()}-${i}`,
        title,
        summary: summary.slice(0, 320) + (summary.length > 320 ? "..." : ""),
        source: "خبرگزاری رسمی اقتصادی / مالیاتی",
        sourceUrl: link || "https://tax.gov.ir",
        pubDate,
        category: title.includes("مودیان") ? "سامانه مودیان" : title.includes("حقوق") ? "حقوق و دستمزد" : "قوانین مالیاتی",
        tags: ["#اخبار_روز", "#مالیات", "#اقتصاد_ایران", "#حسابداری"],
      });
    }
  }

  return items;
}

function cleanText(raw: string): string {
  return raw
    .replace(/<[^>]*>/g, "") // strip HTML tags
    .replace(/&nbsp;/g, " ")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .trim();
}
