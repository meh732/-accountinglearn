// Helper to construct a 3-post package for a curriculum day
function createDay(
  dayNumber: number,
  monthNumber: 1 | 2 | 3,
  weekNumber: number,
  monthTitle: string,
  weekTitle: string,
  title: string,
  summary: string,
  category: ThreeMonthDayItem["category"],
  morningContent: { title: string; content: string; keyRule: string; tags: string[] },
  noonContent: { title: string; content: string; practicalExample: string; tags: string[] },
  eveningContent: {
    title: string;
    question: string;
    options: string[];
    correctOptionIndex: number;
    explanation: string;
    tags: string[];
  }
): ThreeMonthDayItem {
  return {
    id: `day-${dayNumber}`,
    dayNumber,
    monthNumber,
    weekNumber,
    monthTitle,
    weekTitle,
    title,
    summary,
    category,
    posts: [
      // Morning Post: Theory & Concept
      {
        id: `day-${dayNumber}-morning`,
        slot: "morning",
        slotTitle: "🌅 پست صبح (ساعت ۰۹:۰۰) - درس مفهومی و نظری",
        title: morningContent.title,
        category,
        content: morningContent.content,
        keyRule: morningContent.keyRule,
        tags: morningContent.tags,
      },
      // Noon Post: Practical Journal Entry & Case Study
      {
        id: `day-${dayNumber}-noon`,
        slot: "noon",
        slotTitle: "☀️ پست ظهر (ساعت ۱۴:۳۰) - کارگاه عملی و ثبت سند دوبل",
        title: noonContent.title,
        category,
        content: noonContent.content,
        practicalExample: noonContent.practicalExample,
        tags: noonContent.tags,
      },
      // Evening Post: Test Quiz & Channel Member Interactive Challenge
      {
        id: `day-${dayNumber}-evening`,
        slot: "evening",
        slotTitle: "🌙 پست شب (ساعت ۲۰:۰۰) - آزمون روزانه و چالش تعاملی اعضا",
        title: eveningContent.title,
        category,
        content: `📊 <b>آزمون تستی روز شماره ${dayNumber}</b>\nاعضای محترم کانال لطفاً به سوال تستی زیر پاسخ داده و جهت دریافت کارنامه و ثبت سند عملی وارد مینی‌اپ حسابداری شوید:`,
        quizQuestion: eveningContent.question,
        quizOptions: eveningContent.options,
        correctOptionIndex: eveningContent.correctOptionIndex,
        explanation: eveningContent.explanation,
        tags: eveningContent.tags,
      },
    ],
  };
}

